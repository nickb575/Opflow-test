#include <stdint.h>

/* Sentinel in the .reg field meaning "delay .val milliseconds" */
#define PAW_DELAY  0xFFu

typedef struct {
    uint8_t reg;
    uint8_t val;
} paw_regval_t;

/* ---- documented registers (from the datasheet / PX4 header) ---- */
#define PAW_REG_PRODUCT_ID          0x00u   /* expect 0x49 */
#define PAW_REG_REVISION_ID         0x01u
#define PAW_REG_MOTION              0x02u   /* bit7 = MOT, motion since last read */
#define PAW_REG_DELTA_X_L           0x03u
#define PAW_REG_DELTA_X_H           0x04u
#define PAW_REG_DELTA_Y_L           0x05u
#define PAW_REG_DELTA_Y_H           0x06u
#define PAW_REG_SQUAL               0x07u   /* surface quality */
#define PAW_REG_RAWDATA_SUM         0x08u
#define PAW_REG_MAX_RAWDATA         0x09u
#define PAW_REG_MIN_RAWDATA         0x0Au
#define PAW_REG_SHUTTER_LOWER       0x0Bu
#define PAW_REG_SHUTTER_UPPER       0x0Cu
#define PAW_REG_OBSERVATION         0x15u
#define PAW_REG_MOTION_BURST        0x16u   /* 12-byte burst */
#define PAW_REG_POWER_UP_RESET      0x3Au   /* write 0x5A to soft reset */
#define PAW_REG_RESOLUTION          0x4Eu
#define PAW_REG_INVERSE_PRODUCT_ID  0x5Fu   /* expect 0xB6 */

#define PAW_PRODUCT_ID              0x49u
#define PAW_PRODUCT_ID_INVERSE      0xB6u
#define PAW_MOTION_MOT_BIT          0x80u

/* 12-byte Motion_Burst payload, in the order the sensor clocks it out */
typedef struct {
    uint8_t motion;
    uint8_t observation;
    uint8_t delta_x_l;
    uint8_t delta_x_h;
    uint8_t delta_y_l;
    uint8_t delta_y_h;
    uint8_t squal;
    uint8_t rawdata_sum;
    uint8_t max_rawdata;
    uint8_t min_rawdata;
    uint8_t shutter_upper;
    uint8_t shutter_lower;
} paw_burst_t;

